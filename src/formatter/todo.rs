//! DisabledConfigFormatter: the `.rubocop_todo.yml` that `--auto-gen-config` writes, where every
//! cop that found offenses is configured not to find them.

use super::{Ctx, FileOut, Formatter};
use crate::autogen::{self, Val};
use crate::config::value::{Map, Value};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// RuboCop::Options::DEFAULT_MAXIMUM_EXCLUSION_ITEMS
pub const DEFAULT_MAXIMUM_EXCLUSION_ITEMS: i64 = 15;

const EXCLUDED_CONFIG_KEYS: &[&str] = &[
    "AutoCorrect",
    "Description",
    "Enabled",
    "Exclude",
    "Include",
    "Preview",
    "Reference",
    "References",
    "Safe",
    "SafeAutoCorrect",
    "Severity",
    "StyleGuide",
    "VersionAdded",
    "VersionChanged",
    "VersionRemoved",
];

#[derive(Default)]
pub(super) struct Todo {
    /// @cops_with_offenses
    counts: BTreeMap<String, usize>,
    /// @files_with_offenses (absolute paths)
    files: BTreeMap<String, BTreeSet<String>>,
    /// output.path
    path: String,
}

impl Todo {
    pub(super) fn new(path: &Path) -> Todo {
        Todo { path: path.display().to_string(), ..Todo::default() }
    }
}

impl Formatter for Todo {
    fn file_finished(&mut self, _out: &mut String, _cx: &Ctx, f: &FileOut) {
        for o in &f.offenses {
            *self.counts.entry(o.cop.to_string()).or_default() += 1;
            self.files.entry(o.cop.to_string()).or_default().insert(f.path.display().to_string());
        }
    }

    fn finished(&mut self, out: &mut String, cx: &Ctx, _inspected: &[PathBuf]) {
        let g = autogen::gen_context();
        let o = &g.opts;
        let _ = write!(
            out,
            "# This configuration was generated by\n# `{}`\n# {}using RuboCop version {}.\n# The point is for \
             the user to remove these configuration records\n# one by one as the offenses are removed from the \
             code base.\n# Note that changes in the inspected code, or installation of new\n# versions of \
             RuboCop, may require this file to be generated again.\n",
            o.command(),
            if o.timestamp.unwrap_or(true) { format!("on {} ", utc_now()) } else { String::new() },
            crate::config::RUBOCOP_VERSION
        );
        // Syntax isn't a real cop and it can't be disabled.
        self.counts.remove("Lint/Syntax");
        for (cop, &count) in &self.counts {
            out.push('\n');
            self.output_cop(out, cx, cop, count);
        }
        let line = format!("Created {}.\n", self.path);
        if g.stderr {
            eprint!("{line}");
        } else {
            print!("{line}");
        }
    }
}

impl Todo {
    fn exclude_limit(&self) -> i64 {
        autogen::gen_context().opts.exclude_limit_value().unwrap_or(DEFAULT_MAXIMUM_EXCLUSION_ITEMS)
    }

    fn output_cop(&self, out: &mut String, cx: &Ctx, cop: &str, count: usize) {
        let o = &autogen::gen_context().opts;
        let state = autogen::state(cop);
        let mut cfg = state.cfg.clone();
        // set_max
        if !state.limits.is_empty() && self.should_set_max(cx, cop) {
            for (k, v) in &state.limits {
                match cfg.iter_mut().find(|(key, _)| key == k) {
                    Some((_, val)) => *val = Val::Int(*v),
                    None => cfg.push((k.clone(), Val::Int(*v))),
                }
            }
        }
        // output_cop_comments
        if o.offense_counts.unwrap_or(true) {
            let _ = writeln!(out, "# Offense count: {count}");
        }
        let default_cfg = default_config(cx, cop).or_else(|| cx.pwd_config.hash.map(cop).cloned());
        let safe = default_cfg.as_ref().is_none_or(safe_autocorrect);
        if super::supports_autocorrect(cop) {
            if safe {
                out.push_str("# This cop supports safe autocorrection (--autocorrect).\n");
            } else {
                out.push_str("# This cop supports unsafe autocorrection (--autocorrect-all).\n");
            }
        }
        if let Some(default_cfg) = &default_cfg {
            let params: Vec<&str> = default_cfg
                .keys()
                .filter(|k| !EXCLUDED_CONFIG_KEYS.contains(k) && !cfg.iter().any(|(c, _)| c == k))
                .collect();
            if !params.is_empty() {
                let config_params: Vec<&str> = params.iter().copied().filter(|p| !p.starts_with("Supported")).collect();
                let _ = writeln!(out, "# Configuration parameters: {}.", config_params.join(", "));
                for p in &params {
                    let Some(Value::Seq(items)) = default_cfg.get(p) else { continue };
                    if items.is_empty() {
                        continue;
                    }
                    let mut uniq: Vec<&Value> = Vec::new();
                    for v in items.iter() {
                        if !uniq.contains(&v) {
                            uniq.push(v);
                        }
                    }
                    let shown: Vec<String> =
                        uniq.iter().map(|v| if **v == Value::Null { "~".to_string() } else { to_s(v) }).collect();
                    let _ = writeln!(out, "# {p}: {}", shown.join(", "));
                }
            }
        }
        // output_cop_config
        let enforced = o.enforced_style.unwrap_or(true);
        let filtered: Vec<&(String, Val)> =
            cfg.iter().filter(|(k, _)| k != "Enabled" && (enforced || !k.starts_with("EnforcedStyle"))).collect();
        let _ = writeln!(out, "{cop}:");
        for (k, v) in &filtered {
            let _ = writeln!(out, "  {k}: {v}");
        }
        if !filtered.is_empty() {
            return;
        }
        let offending: Vec<&String> = self.files.get(cop).map(|s| s.iter().collect()).unwrap_or_default();
        if !o.no_exclude_limit && offending.len() as i64 > self.exclude_limit() {
            out.push_str("  Enabled: false\n");
            return;
        }
        out.push_str("  Exclude:\n");
        let parent = Path::new(&cx.pwd);
        for exclude in self.excludes(cx, &offending, cop) {
            match exclude {
                Value::Regex(lit) => {
                    let source =
                        lit.strip_prefix('/').and_then(|r| r.rsplit_once('/')).map_or(lit.as_str(), |(s, _)| s);
                    let _ = writeln!(out, "    - !ruby/regexp /{source}/");
                }
                Value::Str(s) if s.starts_with('/') => {
                    let _ = writeln!(out, "    - '{}'", crate::config::relative_path(Path::new(&s), parent));
                }
                // Pathname#relative_path_from raises for a relative path, which is written as is.
                v => {
                    let _ = writeln!(out, "    - '{}'", to_s(&v));
                }
            }
        }
    }

    fn should_set_max(&self, cx: &Ctx, cop: &str) -> bool {
        let o = &autogen::gen_context().opts;
        let default_max = default_config(cx, cop).and_then(|c| c.get("Max").cloned());
        let max_set_in_user_config = cx.pwd_config.for_cop(cop).get("Max").cloned() != default_max;
        if max_set_in_user_config || o.no_exclude_limit {
            return false;
        }
        // In case auto_gen_only_exclude is set, only modify the maximum if the files are not
        // excluded one by one.
        !o.only_exclude.unwrap_or(false) || self.files.get(cop).map_or(0, |s| s.len()) as i64 > self.exclude_limit()
    }

    /// The todo's `Exclude` overrides the default one and any in `.rubocop.yml`, so those are
    /// copied in, unless Exclude merges.
    fn excludes(&self, cx: &Ctx, offending: &[&String], cop: &str) -> Vec<Value> {
        let files: Vec<Value> = offending.iter().map(|f| Value::Str((*f).clone())).collect();
        // `ConfigStore.new.for(parent)`: a fresh store, without the command-line options.
        let Some(config) = autogen::fresh_pwd_config() else { return files };
        let cfg = config.hash.map(cop).cloned().unwrap_or_default();
        let merges = |m: Option<&Map>| {
            m.and_then(|m| m.map("inherit_mode")).and_then(|i| i.get("merge")).is_some_and(|v| match v {
                Value::Seq(items) => items.iter().any(|i| *i == Value::Str("Exclude".into())),
                v => *v == Value::Str("Exclude".into()),
            })
        };
        if merges(Some(&config.hash)) || merges(Some(&cfg)) || config.preview(&autogen::gen_context().store_opts) {
            return files;
        }
        let cop_exclude = cfg.get("Exclude").cloned();
        if let Some(e) = &cop_exclude
            && Some(e) != default_config(cx, cop).as_ref().and_then(|d| d.get("Exclude"))
        {
            let loaded = config.loaded_path.as_deref().map(|p| cx.smart_path(p)).unwrap_or_default();
            eprintln!(
                "`{cop}: Exclude` in `{loaded}` overrides a generated `Exclude` in `.rubocop_todo.yml`. Either remove \
                 `{cop}: Exclude` or add `inherit_mode: merge: - Exclude`."
            );
        }
        let mut all: Vec<Value> = match cop_exclude {
            Some(Value::Seq(items)) => items.to_vec(),
            Some(Value::Null) | None => Vec::new(),
            Some(v) => vec![v],
        };
        all.extend(files);
        let mut uniq: Vec<Value> = Vec::new();
        for v in all {
            if !uniq.contains(&v) {
                uniq.push(v);
            }
        }
        uniq
    }
}

/// `RuboCop::ConfigLoader.default_configuration[cop_name]`
fn default_config(cx: &Ctx, cop: &str) -> Option<Map> {
    cx.default_config.hash.map(cop).cloned()
}

/// `config.fetch('Safe', true) && config.fetch('SafeAutoCorrect', true)`
fn safe_autocorrect(cfg: &Map) -> bool {
    let truthy = |k: &str| cfg.get(k).is_none_or(|v| !matches!(v, Value::Null | Value::Bool(false)));
    truthy("Safe") && truthy("SafeAutoCorrect")
}

/// `#{value}` for a configuration value (Array#join flattens nested arrays).
fn to_s(v: &Value) -> String {
    match v {
        Value::Null => String::new(),
        Value::Bool(b) => b.to_string(),
        Value::Int(i) => i.to_string(),
        Value::Float(f) => crate::helpers::ruby_string::float_to_s(*f),
        Value::Str(s) => s.clone(),
        Value::Sym(s) => s.strip_prefix(':').unwrap_or(s).trim_matches('"').to_string(),
        Value::Regex(lit) => crate::config::value::regexp_to_s(lit),
        Value::Seq(items) => items.iter().map(to_s).collect::<Vec<_>>().join(", "),
        Value::Map(m) => {
            let pairs: Vec<String> = m.0.iter().map(|(k, v)| format!("{k:?} => {}", inspect(v))).collect();
            format!("{{{}}}", pairs.join(", "))
        }
    }
}

/// `#inspect`, for the rare Hash in a default configuration Array.
fn inspect(v: &Value) -> String {
    match v {
        Value::Null => "nil".into(),
        Value::Str(s) => format!("{s:?}"),
        Value::Seq(items) => format!("[{}]", items.iter().map(inspect).collect::<Vec<_>>().join(", ")),
        v => to_s(v),
    }
}

/// `Time.now.utc.to_s`: `2026-10-25 09:28:28 UTC`.
fn utc_now() -> String {
    let secs = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map_or(0, |d| d.as_secs() as i64);
    let (days, rem) = (secs.div_euclid(86_400), secs.rem_euclid(86_400));
    // Howard Hinnant's civil_from_days.
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    format!("{year}-{month:02}-{day:02} {:02}:{:02}:{:02} UTC", rem / 3600, rem % 3600 / 60, rem % 60)
}
