//! `--explain COPS` and the cop-name checks of `--show-cops` / `--show-docs-url`, as RuboCop 1.92.1
//! has them (cli/command/explain.rb, cli/command/cop_names.rb, cop/cop_explanation.rb). The
//! documentation sections are cop/cop_documentation.rb's, read from the comment above each cop
//! class: rbcop has no Ruby sources, so src/cop_docs.txt holds them (scripts/dump-cop-docs.rb).
//!
//! Deliberate difference: a cop of a plugin rbcop does not implement, or of a `require:`d local
//! file, is explained without the sections of its documentation comment.

use rbcop::config::Resolved;
use rbcop::config::validator::{smart_path, to_s};
use rbcop::config::value::{Map, Value};
use rbcop::formatter;
use rbcop::helpers::{cop_registry, did_you_mean};
use std::path::Path;

/// Generated by scripts/dump-cop-docs.rb: `C name`, `S title`, `L text` records.
const DOCS: &str = include_str!("cop_docs.txt");

/// Keys that describe the cop to RuboCop itself (CopExplanation::METADATA_KEYS).
const METADATA_KEYS: &[&str] = &[
    "Description",
    "StyleGuide",
    "Reference",
    "References",
    "Enabled",
    "Safe",
    "SafeAutoCorrect",
    "AutoCorrect",
    "VersionAdded",
    "VersionChanged",
    "Include",
    "Exclude",
    "Details",
    "Preview",
];

/// CopNames#cop_class_for: a registered cop of exactly this name.
fn known(name: &str) -> bool {
    cop_registry::REGISTRY.contains(&name)
}

/// CopNames#known_cop_classes
pub fn known_cops(names: &[String]) -> Vec<&str> {
    names.iter().map(String::as_str).filter(|n| known(n)).collect()
}

/// CopNames#validate_cop_names!: Err is the IncorrectCopNameError message.
pub fn validate_cop_names<'a>(names: impl IntoIterator<Item = &'a str>) -> Result<(), String> {
    let unknown: Vec<String> = names.into_iter().filter(|n| !known(n)).map(unknown_cop_message).collect();
    if unknown.is_empty() { Ok(()) } else { Err(unknown.join("\n")) }
}

fn unknown_cop_message(name: &str) -> String {
    if cop_registry::departments().contains(&name) {
        let example = cop_registry::REGISTRY.iter().find(|c| c.starts_with(&format!("{name}/"))).copied().unwrap_or("");
        return format!("{name} is a department, not a cop. Name one of its cops, such as {example}.");
    }
    let message = format!("Unrecognized cop: {name}.");
    // NameSimilarity.find_similar_names drops the name itself from the dictionary.
    let names: Vec<&str> = cop_registry::REGISTRY.iter().copied().filter(|c| *c != name).collect();
    let similar = did_you_mean::correct(name, &names);
    if similar.is_empty() { message } else { format!("{message}\nDid you mean? {}", similar.join(", ")) }
}

/// CLI::Command::Explain#run: what to print (each explanation on its own `puts`, a blank line
/// between them), then the cop-name check.
pub fn explain(names: &[String], cfg: &Resolved, pwd: &Path) -> (String, Result<(), String>) {
    let mut out = String::new();
    for (i, cop) in known_cops(names).into_iter().enumerate() {
        if i > 0 {
            out.push('\n');
        }
        out.push_str(&explanation(cop, cfg, pwd));
        out.push('\n');
    }
    (out, validate_cop_names(names.iter().map(String::as_str)))
}

/// Cop::CopDocumentation#sections for `cop`.
fn doc_sections(cop: &str) -> Vec<(String, Vec<String>)> {
    let mut out: Vec<(String, Vec<String>)> = Vec::new();
    let head = format!("C {cop}\n");
    let Some(start) = (if DOCS.starts_with(&head) { Some(0) } else { DOCS.find(&format!("\n{head}")).map(|i| i + 1) })
    else {
        return out;
    };
    for line in DOCS[start + head.len()..].lines() {
        if let Some(title) = line.strip_prefix("S ") {
            out.push((title.to_string(), Vec::new()));
        } else if let Some(text) = line.strip_prefix("L ") {
            if let Some(last) = out.last_mut() {
                last.1.push(text.to_string());
            }
        } else {
            break;
        }
    }
    out
}

/// Ruby truthiness.
fn truthy(v: &Value) -> bool {
    !matches!(v, Value::Null | Value::Bool(false))
}

/// `Array#join(', ')`: nested arrays are joined in place, nil is empty.
fn join(items: &[Value]) -> String {
    items
        .iter()
        .map(|v| match v {
            Value::Seq(inner) => join(inner),
            v => to_s(v),
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// Kernel#Array: nil is empty, an Array is itself, anything else is one element.
fn array(v: Option<&Value>) -> Vec<Value> {
    match v {
        None | Some(Value::Null) => Vec::new(),
        Some(Value::Seq(items)) => items.to_vec(),
        Some(v) => vec![v.clone()],
    }
}

/// `drop_while(&:empty?)` from both ends.
fn strip_blank(lines: &[String]) -> Vec<String> {
    let start = lines.iter().position(|l| !l.is_empty()).unwrap_or(lines.len());
    let end = lines.iter().rposition(|l| !l.is_empty()).map_or(start, |i| i + 1);
    lines[start..end.max(start)].to_vec()
}

/// CopExplanation#section
fn section(out: &mut Vec<String>, title: Option<&str>, body: &[String]) {
    if body.is_empty() {
        return;
    }
    out.push(String::new());
    if let Some(t) = title {
        out.push(t.to_string());
        out.push(String::new());
    }
    out.extend(body.iter().map(|l| if l.is_empty() { String::new() } else { format!("  {l}") }));
}

/// Cop::CopExplanation#to_s
fn explanation(cop: &str, cfg: &Resolved, pwd: &Path) -> String {
    // Config#for_cop: the cop's hash with Enabled from enable_cop?.
    let mut c: Map = cfg.hash.map(cop).cloned().unwrap_or_default();
    let enabled = cfg.enable_cop(cop);
    match c.get_mut("Enabled") {
        Some(v) => *v = enabled,
        None => c.insert("Enabled", enabled),
    }
    let fetch = |key: &str, default: Value| c.get(key).cloned().unwrap_or(default);

    let description: Vec<String> = array(c.get("Description"))
        .iter()
        .flat_map(|d| {
            // String#split("\n") drops trailing empty fields.
            let mut parts: Vec<String> = to_s(d).split('\n').map(String::from).collect();
            while parts.last().is_some_and(String::is_empty) {
                parts.pop();
            }
            parts
        })
        .collect();

    let mut properties = vec![
        format!("Enabled:     {}", to_s(&fetch("Enabled", Value::Bool(true)))),
        format!("Safe:        {}", to_s(&fetch("Safe", Value::Bool(true)))),
        format!("Autocorrect: {}", autocorrect_description(cop, &c)),
    ];
    for (key, label) in [("VersionAdded", "Added:       "), ("VersionChanged", "Changed:     ")] {
        if let Some(v) = c.get(key).filter(|v| truthy(v)) {
            properties.push(format!("{label}{}", to_s(v)));
        }
    }
    for (key, label) in [("Include", "Applies to:  "), ("Exclude", "Excludes:    ")] {
        let patterns: Vec<String> = array(c.get(key))
            .iter()
            .filter(|p| !matches!(p, Value::Null))
            .map(|p| match p {
                Value::Str(s) => smart_path(Path::new(s), pwd),
                p => rbcop::config::validator::inspect(p),
            })
            .collect();
        if !patterns.is_empty() {
            properties.push(format!("{label}{}", patterns.join(", ")));
        }
    }

    let mut keys: Vec<&str> = c.keys().filter(|k| !METADATA_KEYS.contains(k)).collect();
    keys.sort_unstable();
    let configuration: Vec<String> = keys
        .iter()
        .map(|k| {
            let v = c.get(k).unwrap();
            format!("{k}: {}", if let Value::Seq(items) = v { join(items) } else { to_s(v) })
        })
        .collect();

    let mut references = formatter::cop_urls(cfg, cop);
    references.extend(formatter::docs_url(cfg, cop));

    let mut lines = vec![cop.to_string()];
    section(&mut lines, None, &description);
    section(&mut lines, Some("Properties"), &properties);
    for (title, mut body) in doc_sections(cop) {
        if title == "Details" {
            body.retain(|l| !description.contains(l));
        }
        section(&mut lines, Some(&title), &strip_blank(&body));
    }
    section(&mut lines, Some("Configuration"), &configuration);
    section(&mut lines, Some("References"), &references);
    lines.join("\n")
}

/// CopExplanation#autocorrect_description
fn autocorrect_description(cop: &str, c: &Map) -> &'static str {
    if !formatter::supports_autocorrect(cop) {
        return "not supported";
    }
    let mode = c.get("AutoCorrect").cloned().unwrap_or(Value::Str("always".into()));
    let always = matches!(&mode, Value::Bool(true)) || matches!(&mode, Value::Str(s) if s == "always");
    let contextual = matches!(&mode, Value::Str(s) if s == "contextual");
    if !always && !contextual {
        return "disabled";
    }
    let safe = c.get("Safe").is_none_or(truthy) && c.get("SafeAutoCorrect").is_none_or(truthy);
    match (safe, contextual) {
        (true, false) => "safe, applied by -a",
        (false, false) => "unsafe, applied by -A only",
        (true, true) => "safe, applied by -a, but through LSP or MCP only on request",
        (false, true) => "unsafe, applied by -A only, but through LSP or MCP only on request",
    }
}
