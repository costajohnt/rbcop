# Regenerates src/helpers/ruby_exceptions/<linux|darwin>.rs for the platform it runs on
# (Lint/ShadowedException's view of Kernel.const_get): every constant path to an Exception subclass
# after a RuboCop run with the default config, and those `require 'resolv'` adds. RuboCop loads a
# cop's file only when the cop is mobilized, and Style/IpAddresses' file requires resolv (and with
# it timeout): those classes resolve only where it loads (#814).
# usage: LC_ALL=C.UTF-8 ruby scripts/dump-ruby-exceptions.rb [-]   (`-`: print to stdout instead)
#   with a `ruby` that loads the pinned RuboCop (scripts/check-generated.sh).
# The result depends on the Ruby version and platform (Errno codes and aliases differ).
os = RUBY_PLATFORM[/linux|darwin/] or abort "dump-ruby-exceptions: no table for #{RUBY_PLATFORM}"
require 'rubocop'
require 'tmpdir'

Dir.mktmpdir do |dir|
  File.write(File.join(dir, 't.rb'), "x = 1\n")
  Dir.chdir(dir) do
    RuboCop::CLI.new.run(['--force-default-config', '--cache', 'false', '--format', 'quiet', '-o', File::NULL, 't.rb'])
  end
end
abort 'dump-ruby-exceptions: resolv is loaded after a default run' if defined?(Resolv)

children = Hash.new do |h, mod|
  h[mod] = mod.constants(false).filter_map do |c|
    next if mod.autoload?(c)
    v = (mod.const_get(c, false) rescue nil)
    [c.to_s, v] if v.is_a?(Module)
  end
end
out = {}
walk = lambda do |mod, prefix, stack|
  return if stack.size > 6
  children[mod].each do |c, v|
    path = prefix.empty? ? c : "#{prefix}::#{c}"
    out[path] = v
    walk.(v, path, stack + [v]) unless stack.include?(v)
  end
end
exceptions = lambda do
  out.clear
  children.clear
  walk.(Object, '', [Object])
  out.reject { |k, _| k.start_with?('Object::') }.select { |_, v| v.is_a?(Class) && v <= Exception }
end
default = exceptions.()
require 'resolv'
exc = exceptions.()
names = {}
exc.each { |path, v| names[v.object_id] ||= v.name || path }

$stdout = File.open(File.expand_path("../src/helpers/ruby_exceptions/#{os}.rs", __dir__), 'w') unless ARGV[0] == '-'
puts <<~RUST
  //! Exception classes the RuboCop #{RuboCop::Version::STRING} process (Ruby #{RUBY_VERSION}, #{RUBY_PLATFORM}) can resolve with
  //! `Kernel.const_get`, for Lint/ShadowedException. Generated by scripts/dump-ruby-exceptions.rb:
  //! (path, class chain `Self Super ... Exception`, Errno value or "", direct subclass of SystemCallError,
  //! resolvable only once `require 'resolv'` ran: where Style/IpAddresses loads).
  //! ponytail: exception classes only; other constants resolve in Ruby too (truthy but never
  //! comparable), regenerate if that ever shows up in a corpus.

  pub static EXCEPTIONS: &[(&str, &str, &str, bool, bool)] = &[
RUST
exc.sort.each do |path, v|
  chain = v.ancestors.select { |a| a.is_a?(Class) && a <= Exception }.map { |a| a.name || names[a.object_id] }
  errno = v.const_defined?(:Errno, false) && v < SystemCallError ? v::Errno.to_s : ''
  puts "    (#{path.inspect}, #{chain.join(' ').inspect}, #{errno.inspect}, #{v.ancestors[1] == SystemCallError}, #{!default.key?(path)}),"
end
puts '];'
