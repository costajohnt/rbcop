# Regenerates src/helpers/ruby_exceptions.rs (Lint/ShadowedException's view of Kernel.const_get):
# every constant path to an Exception subclass after a full RuboCop run with every cop loaded.
# usage: RBENV_VERSION=4.0.6 rbenv exec ruby scripts/dump-ruby-exceptions.rb > src/helpers/ruby_exceptions.rs
# The result depends on the Ruby version and platform (Errno aliases differ).
require 'rubocop'
require 'tmpdir'

config = File.expand_path('../config/all-cops.yml', __dir__)
Dir.mktmpdir do |dir|
  File.write(File.join(dir, 't.rb'), "x = 1\n")
  Dir.chdir(dir) { RuboCop::CLI.new.run(['-c', config, '--cache', 'false', '--format', 'quiet', '-o', File::NULL, 't.rb']) }
end

children = Hash.new do |h, mod|
  h[mod] = mod.constants(false).filter_map do |c|
    next if mod.autoload?(c)
    v = (mod.const_get(c, false) rescue nil)
    [c.to_s, v] if v.is_a?(Module)
  end
end
out = {}
walk = lambda do |mod, prefix, stack|
  return if stack.size > 6
  children[mod].each do |c, v|
    path = prefix.empty? ? c : "#{prefix}::#{c}"
    out[path] = v
    walk.(v, path, stack + [v]) unless stack.include?(v)
  end
end
walk.(Object, '', [Object])
out.reject! { |k, _| k.start_with?('Object::') }
exc = out.select { |_, v| v.is_a?(Class) && v <= Exception }
names = {}
exc.each { |path, v| names[v.object_id] ||= v.name || path }

puts <<~RUST
  //! Exception classes the RuboCop #{RuboCop::Version::STRING} process (Ruby #{RUBY_VERSION}, #{RUBY_PLATFORM}) can resolve with
  //! `Kernel.const_get`, for Lint/ShadowedException. Generated by scripts/dump-ruby-exceptions.rb:
  //! (path, class chain `Self Super ... Exception`, Errno value or "", direct subclass of SystemCallError).
  //! ponytail: exception classes only; other constants resolve in Ruby too (truthy but never
  //! comparable), regenerate if that ever shows up in a corpus.

  pub static EXCEPTIONS: &[(&str, &str, &str, bool)] = &[
RUST
exc.sort.each do |path, v|
  chain = v.ancestors.select { |a| a.is_a?(Class) && a <= Exception }.map { |a| a.name || names[a.object_id] }
  errno = v.const_defined?(:Errno, false) && v < SystemCallError ? v::Errno.to_s : ''
  puts "    (#{path.inspect}, #{chain.join(' ').inspect}, #{errno.inspect}, #{v.ancestors[1] == SystemCallError}),"
end
puts '];'
