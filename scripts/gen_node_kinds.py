"""Generate src/node_kind.rs from the ruby-prism crate's generated bindings.

usage: python3 -I scripts/gen_node_kinds.py target/*/build/ruby-prism-*/out/bindings.rs > src/node_kind.rs
Rerun after upgrading ruby-prism.
"""

import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
body = text[text.index("pub enum Node<'pr> {") :]
body = body[: body.index("\n}\n")]
variants = re.findall(r"^    ([A-Z][A-Za-z]*Node) \{", body, re.M)


def screaming(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


print("// Generated by scripts/gen_node_kinds.py from ruby-prism's bindings. Do not edit.")
print("//! Dense integer ids for Prism node types, used to dispatch nodes to the cops that want them.")
print()
print("use ruby_prism::Node;")
print()
print(f"pub const COUNT: usize = {len(variants)};")
print()
for i, v in enumerate(variants):
    print(f"pub const {screaming(v)}: usize = {i};")
print()
print("pub fn of(node: &Node) -> usize {")
print("    match node {")
for v in variants:
    print(f"        Node::{v} {{ .. }} => {screaming(v)},")
print("    }")
print("}")
print()
print("pub const NAMES: [&str; COUNT] = [")
for v in variants:
    print(f'    "{v}",')
print("];")
